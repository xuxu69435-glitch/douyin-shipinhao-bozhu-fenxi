"""Configuration: local paths and exactly one OpenAI-compatible model configuration."""

import os
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Settings:
    data_dir: Path
    backend_port: int
    backend_token: str
    openai_base_url: str | None
    openai_api_key: str | None
    openai_model: str | None

    @classmethod
    def from_env(cls) -> "Settings":
        default = Path(os.environ.get("LOCALAPPDATA") or Path.home() / ".local" / "share")
        data_dir = Path(os.environ.get("ANALYST_DATA_DIR") or default / "DouyinAnalyst")
        port = int(os.environ.get("ANALYST_BACKEND_PORT", "18763"))
        if not 0 < port < 65536:
            raise ValueError("ANALYST_BACKEND_PORT must be between 1 and 65535")
        token = os.environ.get("ANALYST_BACKEND_TOKEN", "")
        if len(token) < 16:
            raise RuntimeError("ANALYST_BACKEND_TOKEN must be generated by the desktop host")
        return cls(
            data_dir=data_dir,
            backend_port=port,
            backend_token=token,
            openai_base_url=os.environ.get("OPENAI_BASE_URL"),
            openai_api_key=os.environ.get("OPENAI_API_KEY"),
            openai_model=os.environ.get("OPENAI_MODEL"),
        )
